/// Each generated figure: its path under the repository root and its builder.
/// A figure's builder: it renders the SVG or reports the labels that overflow.
type Builder = fn() -> Result<String, Fail>;

fn figures() -> Vec<(&'static str, Builder)> {
    vec![
        ("docs/figures/architecture.svg", architecture),
        ("docs/figures/architecture-narrow.svg", architecture_narrow),
        ("docs/figures/milestones.svg", milestones),
        ("docs/figures/training-pipeline.svg", training_pipeline),
        ("docs/figures/serving-pipeline.svg", serving_pipeline),
        ("docs/figures/geometry-stack.svg", geometry_stack),
        ("docs/figures/geometry/compliant-path.svg", compliant_path),
        ("docs/figures/geometry/operators.svg", operators),
    ]
}

pub fn run(root: &Path, write: bool) -> Result<(), Fail> {
    let mut stale = Vec::new();
    for (rel, build) in figures() {
        let svg = build()?;
        let path = root.join(rel);
        if write {
            std::fs::write(&path, &svg)?;
            println!("wrote {rel}");
        } else if std::fs::read_to_string(&path).ok().as_deref() != Some(svg.as_str()) {
            stale.push(rel);
        }
    }
    if stale.is_empty() {
        if !write {
            println!(
                "figures: all {} generated figures are current",
                figures().len()
            );
        }
        Ok(())
    } else {
        Err(format!(
            "stale generated figures (run `cargo xtask figures --write`): {}",
            stale.join(", ")
        )
        .into())
    }
}
