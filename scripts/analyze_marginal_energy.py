#!/usr/bin/env python3
"""Analyze and compute marginal energy per token (J/token = ΔE/ΔN) on Apple Silicon.

Parses energy measurement log files generated by `scripts/energy_per_token.py`
for 128 and 512 token horizons across repeats, computes marginal energy:
    ΔE = E(512) - E(128)
    ΔN = 512 - 128 = 384 tokens
    Marginal J/token = ΔE / ΔN
and evaluates the pre-registered architectural decision rule.
"""

import argparse
import json
import os
import re
import sys


def parse_energy_file(filepath):
    """Extract metrics from an energy_per_token.py output log."""
    if not os.path.exists(filepath):
        return None

    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    net_j = None
    gross_j = None
    tokens = None
    wall_time = None
    tok_per_sec = None

    m_net = re.search(r"NET energy \(idle removed\)\s*:\s*([0-9.]+)\s*J", content)
    if m_net:
        net_j = float(m_net.group(1))

    m_gross = re.search(r"GROSS energy\s*:\s*([0-9.]+)\s*J", content)
    if m_gross:
        gross_j = float(m_gross.group(1))

    m_tok = re.search(r"tokens\s*:\s*(\d+)", content)
    if m_tok:
        tokens = int(m_tok.group(1))

    m_time = re.search(r"wall time\s*:\s*([0-9.]+)\s*s", content)
    if m_time:
        wall_time = float(m_time.group(1))

    m_rate = re.search(r"decode rate\s*:\s*([0-9.]+)\s*tok/s", content)
    if m_rate:
        tok_per_sec = float(m_rate.group(1))

    if net_j is None or tokens is None:
        return None

    return {
        "tokens": tokens,
        "net_j": net_j,
        "gross_j": gross_j,
        "wall_time": wall_time,
        "tok_per_sec": tok_per_sec,
    }


def analyze_directory(dirpath, repeats=3):
    """Aggregate all runs in the directory and compute marginal metrics."""
    models = {
        "integer": {
            "name": "Integer Bundle (w256, uor-chat)",
            "prefix": "energy-integer",
        },
        "continuous_ff": {
            "name": "Continuous FF Parent (fit256, continuous-ff-generate)",
            "prefix": "energy-continuous-ff",
        },
        "llama_smollm2": {
            "name": "SmolLM2-135M Q4_0 (llama.cpp comparator)",
            "prefix": "energy-llama-smollm2",
        },
    }

    results = {}
    for m_key, m_info in models.items():
        prefix = m_info["prefix"]
        runs_128 = []
        runs_512 = []

        for r in range(1, repeats + 1):
            f128 = os.path.join(dirpath, f"{prefix}-k128-rep{r}.txt")
            f512 = os.path.join(dirpath, f"{prefix}-k512-rep{r}.txt")

            d128 = parse_energy_file(f128)
            d512 = parse_energy_file(f512)

            if d128:
                runs_128.append(d128)
            if d512:
                runs_512.append(d512)

        if not runs_128 and not runs_512:
            continue

        results[m_key] = {
            "name": m_info["name"],
            "runs_128": runs_128,
            "runs_512": runs_512,
        }

    return results


def format_summary(results):
    """Generate text report from analysis results."""
    lines = []
    lines.append("=" * 80)
    lines.append("APPLE SILICON M1 MARGINAL SERVING ENERGY REPORT (Track T3)")
    lines.append("=" * 80)
    lines.append("Instruction Energy vs DRAM Floor Note:")
    lines.append("  This model fits in cache, so the figure is instruction energy,")
    lines.append("  not the DRAM floor.")
    lines.append("=" * 80)

    if not results:
        lines.append("No completed energy measurements found in output directory.")
        lines.append("Run `sudo ./scripts/integer-m1-energy.sh` to produce measurements.")
        lines.append("=" * 80)
        return "\n".join(lines)

    lines.append(f"{'Model':<42} | {'E(128) Net J':<15} | {'E(512) Net J':<15} | {'Marginal J/tok (ΔE/384)':<22}")
    lines.append("-" * 102)

    summary_data = {}
    for m_key, data in results.items():
        runs_128 = data["runs_128"]
        runs_512 = data["runs_512"]

        e128_vals = [r["net_j"] for r in runs_128]
        e512_vals = [r["net_j"] for r in runs_512]

        e128_mean = sum(e128_vals) / len(e128_vals) if e128_vals else 0.0
        e512_mean = sum(e512_vals) / len(e512_vals) if e512_vals else 0.0

        marginal_mean = (e512_mean - e128_mean) / 384.0 if (e128_vals and e512_vals) else 0.0

        # Paired repeats marginal range
        n_pairs = min(len(e128_vals), len(e512_vals))
        paired_marginals = [(e512_vals[i] - e128_vals[i]) / 384.0 for i in range(n_pairs)]
        if paired_marginals:
            min_m = min(paired_marginals)
            max_m = max(paired_marginals)
            m_range_str = f"{marginal_mean:.6f} [{min_m:.6f}..{max_m:.6f}]"
        else:
            m_range_str = f"{marginal_mean:.6f}"

        e128_str = f"{e128_mean:.4f} (n={len(e128_vals)})"
        e512_str = f"{e512_mean:.4f} (n={len(e512_vals)})"

        lines.append(f"{data['name']:<42} | {e128_str:<15} | {e512_str:<15} | {m_range_str:<22}")

        summary_data[m_key] = {
            "name": data["name"],
            "e128_mean_net_j": e128_mean,
            "e128_net_j_repeats": e128_vals,
            "e512_mean_net_j": e512_mean,
            "e512_net_j_repeats": e512_vals,
            "marginal_j_per_token_mean": marginal_mean,
            "marginal_j_per_token_repeats": paired_marginals,
        }

    lines.append("=" * 102)
    lines.append("\nPRE-REGISTERED DECISION EVALUATION:")
    if "integer" in summary_data and "continuous_ff" in summary_data:
        int_m = summary_data["integer"]["marginal_j_per_token_mean"]
        ff_m = summary_data["continuous_ff"]["marginal_j_per_token_mean"]
        lines.append(f"  Integer Marginal J/tok      : {int_m:.6f} J/tok")
        lines.append(f"  Continuous FF Marginal J/tok: {ff_m:.6f} J/tok")
        if int_m >= ff_m:
            lines.append("  VERDICT: Integer J/token >= FF J/token.")
            lines.append("    -> Software product emulation costs energy.")
            lines.append("    -> The stack port then uses grouped LUT accumulation (T-MAC style)")
            lines.append("       and fewer bytes touched, not per-product tables.")
        else:
            lines.append("  VERDICT: Integer J/token < FF J/token.")
            lines.append("    -> Integer kernel shift-add/table design achieves energy advantage.")
            lines.append("    -> Current kernels stay.")
    else:
        lines.append("  Awaiting execution of both integer and continuous FF workloads under sudo.")

    if "llama_smollm2" in summary_data:
        llama_m = summary_data["llama_smollm2"]["marginal_j_per_token_mean"]
        lines.append(f"\n  SmolLM2-135M Q4_0 Reference: {llama_m:.6f} J/tok (Reference point only, not matched quality)")

    lines.append("\n" + "=" * 102)
    return "\n".join(lines), summary_data


def main():
    parser = argparse.ArgumentParser(description="Analyze marginal energy measurements (ΔE/ΔN).")
    parser.add_argument("dir", help="Path to output directory containing energy-*.txt logs")
    parser.add_argument("--repeats", type=int, default=3, help="Number of repeats (default: 3)")
    parser.add_argument("--json", action="store_true", help="Print JSON summary")
    args = parser.parse_args()

    results = analyze_directory(args.dir, args.repeats)
    report_text, summary_data = format_summary(results)

    print(report_text)

    # Save summary files in output directory
    summary_txt_path = os.path.join(args.dir, "summary.txt")
    with open(summary_txt_path, "w", encoding="utf-8") as f:
        f.write(report_text + "\n")

    summary_json_path = os.path.join(args.dir, "summary.json")
    with open(summary_json_path, "w", encoding="utf-8") as f:
        json.dump(summary_data, f, indent=2)

    if args.json:
        print(json.dumps(summary_data, indent=2))


if __name__ == "__main__":
    main()
